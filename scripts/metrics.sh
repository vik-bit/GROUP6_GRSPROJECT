#!/bin/bash
set -e

# ------------------- Resolve project root properly -------------------
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(realpath "$SCRIPT_DIR/..")"

RESULTS_FILE="$PROJECT_ROOT/results.csv"

# ------------------- Wait for Prometheus pod (Updated to 'default' namespace) -------------------
# Based on your cluster, Prometheus is in the default namespace
#PROM_POD=$(kubectl get pods -n default -l app.kubernetes.io/name=prometheus -o jsonpath='{.items[0].metadata.name}')
# Replace the old PROM_POD line with this:
PROM_POD=$(kubectl get pods -n monitoring -l app.kubernetes.io/name=prometheus -o name | head -n 1 | cut -d'/' -f2)

echo "⏳ Waiting for Prometheus pod ($PROM_POD) to be Ready..."
kubectl wait --for=condition=Ready pod/$PROM_POD -n monitoring --timeout=180s
echo "✅ Prometheus pod is Ready"

# ------------------- Port-forward Prometheus (Updated to 'default' namespace) -------------------
# Killing any existing port-forwards to prevent "address already in use" errors
pkill -f "port-forward" || true
kubectl port-forward pod/$PROM_POD 9090:9090 -n monitoring > /dev/null 2>&1 &
sleep 5 # Give it time to establish
echo "📊 Prometheus port-forwarded to localhost:9090"

PROM_URL="http://localhost:9090/api/v1/query"

# ------------------- Config -------------------
USERS=$1
echo "Collecting metrics for $USERS users..."

# ------------------- Ensure CSV exists -------------------
if [ ! -f "$RESULTS_FILE" ]; then
  echo "timestamp,users,rps,p95_latency_ms,cpu_pods,memory_pods,cpu_nodes,memory_nodes,ping_intra_ms,ping_inter_ms,bandwidth_mbps" > "$RESULTS_FILE"
fi

# ------------------- Extract Locust metrics -------------------
# This looks for the summary file generated by your Locust loop
STATS_FILE="$PROJECT_ROOT/load-test/flannel_50u_run_1_stats.csv"

# Check for existence of any locust stats file in the folder
if [ ! -f "$STATS_FILE" ]; then
  # Fallback to the general name if the specific iteration file isn't found
  STATS_FILE=$(ls -t "$PROJECT_ROOT/load-test/"*stats.csv | head -n 1)
fi

echo "📂 Extracting data from: $STATS_FILE"

# Extracting Aggregated RPS (Column 10) and P95 (Column 17)
P95=$(awk -F',' 'NR>1 && $2=="Aggregated"{print $17}' "$STATS_FILE" | tail -1)
RPS=$(awk -F',' 'NR>1 && $2=="Aggregated"{print $10}' "$STATS_FILE" | tail -1)

P95=${P95:-NA}
RPS=${RPS:-NA}

# ------------------- Prometheus metrics function -------------------
query_prometheus() {
  local result
  result=$(curl -sG "$PROM_URL" --data-urlencode "query=$1" \
            | jq -r '.data.result[0].value[1]' 2>/dev/null)
  if [[ -z "$result" || "$result" == "null" ]]; then
    echo "NA"
  else
    echo "$result"
  fi
}

echo "📊 Fetching Prometheus metrics..."

# Pod CPU (cores)
CPU_PODS=$(query_prometheus 'sum(rate(container_cpu_usage_seconds_total{container!=""}[1m]))')
[[ "$CPU_PODS" == "NA" ]] || CPU_PODS=$(printf "%.2f" "$CPU_PODS")

# Pod Memory (bytes → MiB)
MEM_PODS_RAW=$(query_prometheus 'sum(container_memory_usage_bytes{container!=""})')
if [[ "$MEM_PODS_RAW" != "NA" ]]; then
    MEM_PODS=$(echo "scale=2; $MEM_PODS_RAW / 1024 / 1024" | bc)
else
    MEM_PODS="NA"
fi

# Node CPU (%)
CPU_NODES=$(query_prometheus '100 - (avg(rate(node_cpu_seconds_total{mode="idle"}[1m])) * 100)')
[[ "$CPU_NODES" == "NA" ]] || CPU_NODES=$(printf "%.2f" "$CPU_NODES")

# Node Memory (bytes → MiB)
MEM_NODES_RAW=$(query_prometheus 'sum(node_memory_MemTotal_bytes - node_memory_MemAvailable_bytes)')
if [[ "$MEM_NODES_RAW" != "NA" ]]; then
    MEM_NODES=$(echo "scale=2; $MEM_NODES_RAW / 1024 / 1024" | bc)
else
    MEM_NODES="NA"
fi

# ------------------- Network (ping intra/inter) -------------------
POD_B=$(kubectl get pods -l app=service-b -o jsonpath="{.items[0].metadata.name}" 2>/dev/null || echo "")
POD_C=$(kubectl get pods -l app=service-c -o jsonpath="{.items[0].metadata.name}" 2>/dev/null || echo "")

if [ -n "$POD_B" ] && [ -n "$POD_C" ]; then
  IP_B=$(kubectl get pod "$POD_B" -o jsonpath="{.status.podIP}")
  IP_C=$(kubectl get pod "$POD_C" -o jsonpath="{.status.podIP}")
  PING_INTRA=$(ping -c 3 "$IP_B" | tail -1 | awk -F '/' '{print $5}')
  PING_INTER=$(ping -c 3 "$IP_C" | tail -1 | awk -F '/' '{print $5}')
else
  PING_INTRA="NA"
  PING_INTER="NA"
fi

# ------------------- iperf3 bandwidth (The Fixed Version) -------------------
echo "🚀 Running iperf bandwidth test..."

# 1. Get the IP of your iperf3-server
IPERF_SERVER_IP=$(kubectl get pod iperf3-server -o jsonpath='{.status.podIP}' 2>/dev/null || echo "")

if [ -n "$IPERF_SERVER_IP" ]; then
    # 2. 'kubectl run' creates a temporary pod, runs the test, and '--rm' deletes it after
    # We use '--connect-timeout 5000' to ensure it doesn't hang forever
    IPERF_RAW=$(kubectl run iperf-client-temp --rm -i --restart=Never --image=networkstatic/iperf3 -- iperf3 -c "$IPERF_SERVER_IP" -J 2>/dev/null || echo "")
    
    # 3. Extract the speed from the JSON output
    BANDWIDTH_BPS=$(echo "$IPERF_RAW" | jq -r '.end.sum_received.bits_per_second' 2>/dev/null || echo "")
    
    if [[ -n "$BANDWIDTH_BPS" && "$BANDWIDTH_BPS" != "null" ]]; then
        BANDWIDTH_MBPS=$(echo "scale=3; $BANDWIDTH_BPS / 1000000" | bc)
    else
        BANDWIDTH_MBPS="NA"
    fi
else
    echo "⚠️ iperf3-server pod not found!"
    BANDWIDTH_MBPS="NA"
fi
#--------------- Save results -------------------
TIMESTAMP=$(date +"%Y-%m-%d %H:%M:%S")
echo "$TIMESTAMP,$USERS,$RPS,$P95,$CPU_PODS,$MEM_PODS,$CPU_NODES,$MEM_NODES,$PING_INTRA,$PING_INTER,$BANDWIDTH_MBPS" >> "$RESULTS_FILE"

echo "✅ Results appended to $RESULTS_FILE"
